#!/usr/bin/env bash
# Prepares the Ubuntu VPS for the existing release scripts (remote.sh,
# release.sh, switch.py, worker.sh): HD_MARKETING_PRODUCTION_DEPLOYMENT.md
# sections 3-7. Idempotent; run from a checkout of main:
#
#   sudo bash deploy/production/bootstrap-vps.sh --domain hdmarketing.tech \
#     --redirect-www --deploy-host 187.127.206.178 \
#     --deploy-key ~/hd-crm-github-deploy.pub --server-env ~/hd-crm-server.env
#
# Without --apply it only reads and reports. --apply changes only what the
# report lists. It never changes SSH settings, the firewall, Docker, Supabase
# or live traffic (no release, no slot switch), never removes an authorized
# key, keeps every replaced file as *.previous, leaves disabled sites in
# sites-available, and never prints a secret.
# --print-site writes the rendered Nginx site to stdout (no root; used by CI).
set -Eeuo pipefail
umask 022

APP_USER=crm-prod
BASE=/srv/hd-crm/production
ETC=/etc/hd-crm/production
SERVER_ENV=$ETC/server.env
HELPER=/usr/local/sbin/hd-crm-switch
SUDOERS=/etc/sudoers.d/hd-crm-switch
SUDOERS_RULE="$APP_USER ALL=(root) NOPASSWD: $HELPER production *"
ACTIVE_INCLUDE=/etc/nginx/hd-crm/production.conf
LIMITS=/etc/nginx/conf.d/hd-crm-limits.conf
SITE=/etc/nginx/sites-available/hd-crm
SITE_LINK=/etc/nginx/sites-enabled/hd-crm
WEBROOT=/var/www/letsencrypt
# Sites this script disables are moved here, never deleted.
DISABLED_SITES=/etc/nginx/hd-crm-disabled-sites
RENEW_HOOK=/etc/letsencrypt/renewal-hooks/deploy/reload-nginx
# remote.sh runs releases with exactly this PATH.
RELEASE_PATH=/usr/local/bin:/usr/bin:/bin
HERE=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
REPO=$(cd "$HERE/../.." && pwd)

valid_domain() {
  [[ "$1" =~ ^([a-z0-9]([a-z0-9-]*[a-z0-9])?\.)+[a-z]{2,63}$ ]]
}

# Prints "type key" for a file holding exactly one plain public key line.
public_key() {
  local file=$1 type body extra
  [[ -f "$file" ]] || { echo "Public key file not found: $file" >&2; return 1; }
  if grep -q 'PRIVATE KEY' "$file"; then
    echo "$file is a private key; pass the .pub file" >&2; return 1
  fi
  [[ "$(grep -c . "$file")" == 1 ]] || { echo "$file must hold exactly one public key line" >&2; return 1; }
  read -r type body extra < <(grep . "$file")
  case "$type" in
    ssh-ed25519|ecdsa-sha2-nistp256|ecdsa-sha2-nistp384|ecdsa-sha2-nistp521|ssh-rsa) ;;
    *) echo "$file: unsupported key type, or the line already has options" >&2; return 1 ;;
  esac
  [[ "$body" =~ ^[A-Za-z0-9+/]+=*$ ]] || { echo "$file: malformed public key" >&2; return 1; }
  if command -v ssh-keygen >/dev/null && ! ssh-keygen -lf "$file" >/dev/null 2>&1; then
    echo "$file: ssh-keygen cannot read this public key" >&2; return 1
  fi
  printf '%s %s\n' "$type" "$body"
}

# Adds the key with `restrict` (no forwarding, no terminal; commands, scp and
# sftp still work) unless it is already authorized. Other lines are never
# changed. Prints "added" or "present".
authorize_key() {
  local key file=$2
  key=$(public_key "$1") || return 1
  if [[ -f "$file" ]] && grep -qF -- "${key#* }" "$file"; then echo present; return 0; fi
  if [[ -s "$file" && -n "$(tail -c1 "$file")" ]]; then printf '\n' >> "$file"; fi
  printf 'restrict %s hd-crm-github-actions\n' "$key" >> "$file"
  echo added
}

# The production site from site.conf.example for one domain, plus optional
# www -> domain redirects that reuse the same certificate.
render_site() {
  local domain=$1 www=$2
  echo "# Generated by deploy/production/bootstrap-vps.sh from site.conf.example; change the template, not this file."
  sed -e '1{/^# Replace/d;}' -e "s/crm\.example\.com/$domain/g" "$HERE/site.conf.example"
  [[ "$www" == yes ]] || return 0
  cat <<EOF
# www.$domain redirects to the main address (--redirect-www).
server {
    listen 80;
    server_name www.$domain;
    location /.well-known/acme-challenge/ { root $WEBROOT; }
    location / { return 301 https://$domain\$request_uri; }
}
server {
    listen 443 ssl;
    server_name www.$domain;
    ssl_certificate /etc/letsencrypt/live/$domain/fullchain.pem;
    ssl_certificate_key /etc/letsencrypt/live/$domain/privkey.pem;
    ssl_protocols TLSv1.2 TLSv1.3;
    add_header Strict-Transport-Security "max-age=31536000" always;
    access_log /var/log/nginx/crm-production-access.log crm_safe;
    location / { return 301 https://$domain\$request_uri; }
}
EOF
}

# Checks a server.env without printing values: names and rules only.
check_server_env() {
  python3 - "$1" "$2" <<'PY'
import base64, json, re, sys
path, domain = sys.argv[1:3]
env, problems = {}, []
for number, line in enumerate(open(path, encoding="utf-8"), 1):
    line = line.strip()
    if not line or line.startswith("#"):
        continue
    match = re.match(r"^([A-Za-z_][A-Za-z0-9_]*)=(.*)$", line)
    if not match:
        problems.append(f"line {number} is not KEY=value")
        continue
    value = match.group(2)
    if len(value) >= 2 and value[0] == value[-1] and value[0] in "'\"":
        value = value[1:-1]
    env[match.group(1)] = value
def need(key, ok, rule):
    if not ok:
        problems.append(f"{key}: {rule}")
placeholder = lambda v: re.match(r"(?i)^(replace[-_ ]|your[-_ ]|<)", v or "")
for key in ("SUPABASE_URL", "SUPABASE_SERVICE_ROLE_KEY", "ACCOUNTS_PIN_PEPPER", "WEBHOOK_SECRET"):
    need(key, env.get(key) and not placeholder(env[key]), "required, real value")
need("NODE_ENV", env.get("NODE_ENV") == "production", "must be production")
need("FRONTEND_URL", env.get("FRONTEND_URL") == f"https://{domain}", f"must be exactly https://{domain}")
need("SUPABASE_URL", re.fullmatch(r"https://[a-z0-9-]+\.supabase\.co", env.get("SUPABASE_URL", "")),
     "must be https://<project>.supabase.co without a trailing slash")
need("CALL_PROVIDER", env.get("CALL_PROVIDER") == "manual", "must be manual")
for key in ("ACCOUNTS_PIN_PEPPER", "WEBHOOK_SECRET", "ACCOUNT_OTP_SECRET"):
    if key in env:
        need(key, len(env[key]) >= 32, "needs at least 32 characters")
need("TRUST_PROXY", env.get("TRUST_PROXY", "loopback") != "true" and not env.get("TRUST_PROXY", "").isdigit(),
     "never true or a hop count")
need("REQUIRE_AGENT_MFA", env.get("REQUIRE_AGENT_MFA", "false") in ("true", "false"), "true or false")
key = env.get("SUPABASE_SERVICE_ROLE_KEY", "")
try:
    role = json.loads(base64.urlsafe_b64decode(key.split(".")[1] + "==")).get("role")
except Exception:
    role = None
need("SUPABASE_SERVICE_ROLE_KEY", role != "anon" and not key.startswith("sb_publishable_"),
     "is the public anon key; use the service-role key")
for name in env:
    need(name, not name.startswith(("DEV_", "VITE_")) and name != "PORT", "development or browser setting; remove it")
print("\n".join(problems))
sys.exit(1 if problems else 0)
PY
}

usage() {
  echo "Usage: sudo bash $0 --domain DOMAIN [--redirect-www] [--deploy-host HOST]" >&2
  echo "       [--deploy-key FILE.pub] [--server-env FILE] [--apply] | --print-site --domain DOMAIN [--redirect-www]" >&2
  exit 2
}

# ---------------------------------------------------------------- reporting
todo=0; manual=0; changed=0; mode=check; tmp=
say() { printf '  %-7s %s\n' "$1" "$2"; }
ok() { say OK "$1"; }
warn() { say WARN "$1"; }
section() { printf '\n%s\n' "$1"; }
# True when the caller should make the change now (apply mode).
need() {
  if [[ "$mode" == apply ]]; then say APPLY "$1"; changed=$((changed + 1)); return 0; fi
  say TODO "$1"; todo=$((todo + 1)); return 1
}
manual_step() { say MANUAL "$1"; manual=$((manual + 1)); }
attrs() { stat -c '%U:%G %a' "$1" 2>/dev/null; }

ensure_dir() { # path owner group mode
  if [[ -d "$1" && "$(attrs "$1")" == "$2:$3 $4" ]]; then ok "$1 ($2:$3 $4)"
  elif need "$1 owned by $2:$3, mode $4"; then install -d -o "$2" -g "$3" -m "$4" "$1"; fi
}
# Installs file $2 at $1 unless identical; a replaced file is kept as $1.previous.
ensure_file() { # target source owner group mode label
  if [[ -f "$1" ]] && cmp -s "$2" "$1" && [[ "$(attrs "$1")" == "$3:$4 $5" ]]; then ok "$6"; return 0; fi
  if need "$6"; then
    if [[ -f "$1" ]] && ! cmp -s "$2" "$1"; then cp -p "$1" "$1.previous"; fi
    install -o "$3" -g "$4" -m "$5" "$2" "$1"
  fi
}

# --------------------------------------------------------------------- main
main() {
  local domain='' www=no deploy_host='' key_file='' env_in='' print_site=no
  while (($#)); do
    case "$1" in
      --apply) mode=apply ;;
      --print-site) print_site=yes ;;
      --redirect-www) www=yes ;;
      --domain) domain=${2:-}; shift ;;
      --deploy-host) deploy_host=${2:-}; shift ;;
      --deploy-key) key_file=${2:-}; shift ;;
      --server-env) env_in=${2:-}; shift ;;
      *) usage ;;
    esac
    shift
  done
  valid_domain "$domain" || { echo "Give --domain as a lower-case host name such as hdmarketing.tech" >&2; exit 2; }
  if [[ "$print_site" == yes ]]; then render_site "$domain" "$www"; return 0; fi
  deploy_host=${deploy_host:-$domain}
  # Same rule as remote.sh: the known-hosts lines must name this exact host.
  [[ "$deploy_host" =~ ^[a-zA-Z0-9][a-zA-Z0-9.-]*$ ]] || { echo "Invalid --deploy-host" >&2; exit 2; }
  if [[ -n "$key_file" ]]; then public_key "$key_file" >/dev/null || exit 2; fi
  if [[ -n "$env_in" && ! -f "$env_in" ]]; then echo "Settings file not found: $env_in" >&2; exit 2; fi
  [[ "$(uname -s)" == Linux && "$EUID" == 0 ]] || { echo "Run with sudo on the Ubuntu VPS" >&2; exit 1; }

  tmp=$(mktemp -d); trap 'rm -rf -- "$tmp"' EXIT
  . /etc/os-release
  echo "HD Marketing CRM VPS bootstrap: $mode mode, $PRETTY_NAME, checkout $(git -C "$REPO" rev-parse --short HEAD 2>/dev/null || echo unknown)"

  section "Packages and runtime"
  local missing=() pair command
  for pair in nginx:nginx certbot:certbot python3:python3 curl:curl flock:util-linux tar:tar git:git age:age xz:xz-utils visudo:sudo openssl:openssl; do
    command -v "${pair%%:*}" >/dev/null || missing+=("${pair#*:}")
  done
  if ((${#missing[@]} == 0)); then ok "required packages installed"
  elif need "install packages: ${missing[*]}"; then
    apt-get update -qq && DEBIAN_FRONTEND=noninteractive apt-get install -y -qq "${missing[@]}"
  fi
  local major; major=$(PATH=$RELEASE_PATH node -p 'process.versions.node.split(".")[0]' 2>/dev/null || true)
  if [[ "$major" == 24 ]]; then ok "Node $(PATH=$RELEASE_PATH node -v) at $(PATH=$RELEASE_PATH command -v node) (kept as installed)"
  elif [[ -z "$major" ]]; then
    if need "install Node 24 with deploy/production/install-node.sh"; then bash "$HERE/install-node.sh"; fi
  else manual_step "Node $(PATH=$RELEASE_PATH node -v) is installed; production uses Node 24. Upgrade it deliberately, then rerun."; fi
  # Read the version from its package; running pm2 as root would start a root daemon.
  local pm2_version; pm2_version=$(PATH=$RELEASE_PATH node -p "require(require('path').join('$(PATH=$RELEASE_PATH npm root -g 2>/dev/null)','pm2/package.json')).version" 2>/dev/null || true)
  if [[ -n "$pm2_version" ]] && PATH=$RELEASE_PATH command -v pm2 >/dev/null; then ok "PM2 $pm2_version"
  elif need "install PM2 6 (npm install --global pm2@6)"; then PATH=$RELEASE_PATH npm install --global pm2@6; fi

  section "Account $APP_USER and release folders"
  if id "$APP_USER" >/dev/null 2>&1; then ok "user $APP_USER exists"
  elif need "create user $APP_USER (no password)"; then adduser --disabled-password --gecos '' "$APP_USER"; fi
  local shell; shell=$(getent passwd "$APP_USER" | cut -d: -f7 || true)
  case "$shell" in */nologin|*/false) manual_step "$APP_USER has shell $shell; releases need a login shell such as /bin/bash" ;; esac
  if [[ -e /var/lib/systemd/linger/$APP_USER ]]; then ok "lingering enabled (releases run as systemd user jobs)"
  elif need "enable lingering for $APP_USER"; then loginctl enable-linger "$APP_USER"; fi
  local service=pm2-$APP_USER
  if systemctl is-enabled --quiet "$service" 2>/dev/null && systemctl is-active --quiet "$service"; then
    ok "$service service enabled and running (release.sh requires it)"
  elif need "enable and start the $service service"; then
    [[ -f /etc/systemd/system/$service.service ]] || PATH=$RELEASE_PATH pm2 startup systemd -u "$APP_USER" --hp "/home/$APP_USER"
    systemctl enable --now "$service"
  fi
  ensure_dir /srv/hd-crm root root 755
  ensure_dir "$BASE" "$APP_USER" "$APP_USER" 755
  ensure_dir "$BASE/releases" "$APP_USER" "$APP_USER" 755
  ensure_dir "$BASE/assets" "$APP_USER" "$APP_USER" 755
  ensure_dir /etc/hd-crm root root 755
  ensure_dir "$ETC" root "$APP_USER" 750
  printf 'https://%s\n' "$domain" > "$tmp/origin"
  ensure_file "$BASE/origin" "$tmp/origin" "$APP_USER" "$APP_USER" 644 "public address for release checks ($BASE/origin)"
  if [[ -f "$BASE/active" ]]; then ok "active release: $(cat "$BASE/active")"; else ok "no release yet (the first release creates $BASE/active)"; fi

  section "Deployment SSH access"
  local ssh_dir=/home/$APP_USER/.ssh auth=/home/$APP_USER/.ssh/authorized_keys key fingerprint
  ensure_dir "$ssh_dir" "$APP_USER" "$APP_USER" 700
  if [[ -n "$key_file" ]]; then
    key=$(public_key "$key_file"); fingerprint=$(ssh-keygen -lf "$key_file" | awk '{print $2}')
    if [[ -f "$auth" ]] && grep -qF -- "${key#* }" "$auth"; then
      ok "deploy key $fingerprint is authorized"
      grep -F -- "${key#* }" "$auth" | grep -qE '^restrict[ ,]' || warn "deploy key $fingerprint is authorized without 'restrict'; left unchanged"
    elif need "authorize deploy key $fingerprint for $APP_USER with 'restrict'"; then
      (umask 077; authorize_key "$key_file" "$auth" >/dev/null)
      chown "$APP_USER:$APP_USER" "$auth"; chmod 600 "$auth"
    fi
  fi
  if [[ -f "$auth" ]]; then
    if [[ "$(attrs "$auth")" == "$APP_USER:$APP_USER 600" ]]; then ok "$auth ($(grep -cvE '^\s*(#|$)' "$auth") key line(s); none removed)"
    elif need "$auth owned by $APP_USER, mode 600"; then chown "$APP_USER:$APP_USER" "$auth"; chmod 600 "$auth"; fi
  elif [[ -z "$key_file" ]]; then manual_step "no deploy key authorized yet; rerun with --deploy-key FILE.pub"; fi
  # What sshd applies to this account: key login, PAM session for
  # systemd-run --user, and sftp for scp (OpenSSH 9+ scp uses sftp).
  local effective; effective=$(sshd -T -C "user=$APP_USER,host=github-actions.invalid,addr=192.0.2.10" 2>/dev/null || true)
  if [[ -z "$effective" ]]; then manual_step "could not read the effective SSH settings (sshd -T)"
  else
    grep -qx 'pubkeyauthentication yes' <<<"$effective" && ok "SSH key login allowed for $APP_USER" || manual_step "SSH public key login is disabled for $APP_USER"
    grep -qx 'usepam yes' <<<"$effective" && ok "SSH sessions start a user session (systemd-run --user works)" || manual_step "UsePAM is off; systemd-run --user needs a PAM session"
    grep -q '^subsystem sftp ' <<<"$effective" && ok "sftp available (scp uploads)" || manual_step "no sftp subsystem; release uploads use scp over sftp"
    # Patterns such as *@10.0.0.* are matched, never expanded as file names.
    local tokens=() token groups; groups=" $(id -nG "$APP_USER" 2>/dev/null) "
    read -ra tokens <<<"$(sed -n 's/^allowusers //p' <<<"$effective")"
    if ((${#tokens[@]})); then
      local allowed=no; for token in "${tokens[@]}"; do [[ "$APP_USER" == ${token%%@*} ]] && allowed=yes; done
      [[ "$allowed" == yes ]] && ok "AllowUsers includes $APP_USER" || manual_step "AllowUsers does not include $APP_USER (SSH settings are not changed here)"
    fi
    read -ra tokens <<<"$(sed -n 's/^allowgroups //p' <<<"$effective")"
    if ((${#tokens[@]})); then
      local member=no; for token in "${tokens[@]}"; do [[ "$groups" == *" $token "* ]] && member=yes; done
      [[ "$member" == yes ]] && ok "AllowGroups includes a group of $APP_USER" || manual_step "AllowGroups excludes $APP_USER"
    fi
    read -ra tokens <<<"$(sed -n 's/^denyusers //p' <<<"$effective")"
    for token in ${tokens[@]+"${tokens[@]}"}; do [[ "$APP_USER" == ${token%%@*} ]] && manual_step "DenyUsers blocks $APP_USER"; done
    read -ra tokens <<<"$(sed -n 's/^denygroups //p' <<<"$effective")"
    for token in ${tokens[@]+"${tokens[@]}"}; do [[ "$groups" == *" $token "* ]] && manual_step "DenyGroups blocks $APP_USER"; done
  fi

  section "Traffic switch helper"
  ensure_file "$HELPER" "$HERE/switch.py" root root 755 "switch helper $HELPER matches this checkout"
  printf '%s\n' "$SUDOERS_RULE" > "$tmp/sudoers"; chmod 440 "$tmp/sudoers"
  if [[ -f "$SUDOERS" ]]; then
    if cmp -s "$tmp/sudoers" "$SUDOERS"; then ok "$APP_USER may run only the switch helper as root ($SUDOERS)"
    else manual_step "$SUDOERS differs from the expected single rule; review it by hand (not changed)"; fi
  elif need "allow $APP_USER to run only the switch helper as root ($SUDOERS)"; then
    visudo -cqf "$tmp/sudoers"
    install -o root -g root -m 440 "$tmp/sudoers" "$SUDOERS"
    visudo -cq || { rm -f "$SUDOERS"; echo "sudo configuration invalid; $SUDOERS removed" >&2; exit 1; }
  fi

  section "TLS certificate"
  local live=/etc/letsencrypt/live/$domain cert_ok=yes names
  if [[ -f "$live/fullchain.pem" && -f "$live/privkey.pem" ]]; then
    names=$(openssl x509 -in "$live/fullchain.pem" -noout -ext subjectAltName 2>/dev/null | tr ',' '\n' | sed -n 's/.*DNS://p')
    grep -qx "$domain" <<<"$names" && ok "certificate covers $domain" || { manual_step "certificate does not cover $domain"; cert_ok=no; }
    if [[ "$www" == yes ]]; then
      grep -qx "www.$domain" <<<"$names" && ok "certificate covers www.$domain" || { manual_step "certificate does not cover www.$domain (expand it with certbot, then rerun)"; cert_ok=no; }
    fi
    openssl x509 -in "$live/fullchain.pem" -noout -checkend $((21 * 86400)) >/dev/null && ok "certificate valid for more than 21 days" || warn "certificate expires within 21 days"
  else
    manual_step "no certificate at $live (section 7 of the deployment guide); Nginx is left unchanged"; cert_ok=no
  fi

  section "Nginx"
  ensure_dir /etc/nginx/hd-crm root root 755
  ensure_dir "$WEBROOT" root root 755
  if [[ -f "$ACTIVE_INCLUDE" ]]; then ok "release include $ACTIVE_INCLUDE exists: $(head -c 60 "$ACTIVE_INCLUDE" | head -1) (never changed here)"
  elif need "create $ACTIVE_INCLUDE with the 503 holding page (replaced by the first release)"; then
    printf 'location / { return 503; }\n' > "$ACTIVE_INCLUDE"; chmod 644 "$ACTIVE_INCLUDE"
  fi
  render_site "$domain" "$www" > "$tmp/site"
  # Sites that would compete for these names: Ubuntu's default and any
  # enabled site naming the domain (e.g. a placeholder). Files are kept.
  local conflicts=() entry
  for entry in /etc/nginx/sites-enabled/*; do
    [[ -e "$entry" || -L "$entry" ]] || continue
    [[ "$(basename "$entry")" == hd-crm ]] && continue
    if [[ "$(basename "$entry")" == default ]] || grep -hE '^\s*server_name\s' "$entry" 2>/dev/null | tr -s ' \t;' '\n\n\n' | grep -qxE "(www\.)?${domain//./\\.}"; then
      conflicts+=("$entry")
    fi
  done
  for entry in /etc/nginx/conf.d/*.conf; do
    [[ -f "$entry" ]] || continue
    if grep -hE '^\s*server_name\s' "$entry" | tr -s ' \t;' '\n\n\n' | grep -qxE "(www\.)?${domain//./\\.}"; then manual_step "$entry also serves $domain; disable it by hand (not changed)"; fi
  done
  local site_current=no
  [[ -f "$SITE" ]] && cmp -s "$tmp/site" "$SITE" && [[ "$(readlink "$SITE_LINK" 2>/dev/null)" == "$SITE" ]] && site_current=yes
  if [[ "$site_current" == yes && ${#conflicts[@]} -eq 0 && -f "$LIMITS" ]] && cmp -s "$HERE/nginx.conf.example" "$LIMITS"; then
    ok "CRM site for $domain enabled$( [[ "$www" == yes ]] && echo ", www redirects to it")"
  elif [[ "$cert_ok" != yes ]]; then
    manual_step "CRM site not enabled until the certificate covers the names above"
  else
    for entry in ${conflicts[@]+"${conflicts[@]}"}; do need "disable sites-enabled/$(basename "$entry") (it serves $domain or is Ubuntu's default; the file stays in sites-available)" || true; done
    if need "install the rate-limit file, the CRM site for $domain and enable it; holding page until the first release"; then
      enable_site "$domain" "$tmp" ${conflicts[@]+"${conflicts[@]}"}
    fi
  fi
  if [[ "$mode" == check ]]; then
    nginx -t >/dev/null 2>&1 && ok "current Nginx configuration is valid" || manual_step "current Nginx configuration fails nginx -t"
  fi

  section "Certificate renewal"
  local renewal=/etc/letsencrypt/renewal/$domain.conf
  printf '#!/bin/sh\n/usr/sbin/nginx -t && /bin/systemctl reload nginx\n' > "$tmp/hook"
  ensure_file "$RENEW_HOOK" "$tmp/hook" root root 755 "Nginx reload after each renewal ($RENEW_HOOK)"
  if systemctl is-enabled --quiet certbot.timer 2>/dev/null && systemctl is-active --quiet certbot.timer; then ok "certbot.timer enabled"
  elif need "enable certbot.timer"; then systemctl enable --now certbot.timer; fi
  if [[ -f "$renewal" ]] && grep -q '^authenticator = webroot' "$renewal" && grep -qF "$WEBROOT" "$renewal"; then
    ok "renewal uses $WEBROOT through the running Nginx"
  elif [[ -f "$renewal" ]]; then
    if [[ "$(readlink "$SITE_LINK" 2>/dev/null)" != "$SITE" ]]; then
      say TODO "switch renewal to $WEBROOT after the CRM site is enabled (rerun --apply)"; todo=$((todo + 1))
    elif need "renew through $WEBROOT (certbot reconfigure; includes a test renewal)"; then
      certbot reconfigure --non-interactive --cert-name "$domain" --webroot --webroot-path "$WEBROOT" >/dev/null 2>&1 \
        && ok "renewal switched to webroot" || warn "certbot reconfigure failed; renewal keeps its current method"
    fi
  fi

  section "Production settings ($SERVER_ENV)"
  if [[ -n "$env_in" ]]; then
    local problems; problems=$(check_server_env "$env_in" "$domain" || true)
    if [[ -n "$problems" ]]; then
      manual_step "$env_in is not ready (nothing installed):"; sed 's/^/            /' <<<"$problems"
    elif [[ -f "$SERVER_ENV" ]] && cmp -s "$env_in" "$SERVER_ENV"; then
      ok "installed settings already match $env_in"
      if [[ "$mode" == apply ]]; then shred -u "$env_in" 2>/dev/null || rm -f "$env_in"; ok "uploaded copy deleted"; fi
    elif [[ -f "$SERVER_ENV" ]] && ! preserved_secrets_match "$SERVER_ENV" "$env_in"; then
      manual_step "$env_in changes ACCOUNTS_PIN_PEPPER, ACCOUNT_OTP_SECRET or META_TOKEN_ENCRYPTION_KEY; keep the installed values (nothing installed)"
    elif need "install $env_in as $SERVER_ENV (root:$APP_USER 640) and delete the uploaded copy"; then
      if [[ -f "$SERVER_ENV" ]]; then cp -p "$SERVER_ENV" "$SERVER_ENV.previous"; fi
      install -o root -g "$APP_USER" -m 640 "$env_in" "$SERVER_ENV"
      shred -u "$env_in" 2>/dev/null || rm -f "$env_in"
    fi
  fi
  if [[ -f "$SERVER_ENV" ]]; then
    if [[ "$(attrs "$SERVER_ENV")" == "root:$APP_USER 640" ]]; then ok "permissions root:$APP_USER 640"
    elif need "$SERVER_ENV owned by root:$APP_USER, mode 640"; then chown "root:$APP_USER" "$SERVER_ENV"; chmod 640 "$SERVER_ENV"; fi
    runuser -u "$APP_USER" -- test -r "$SERVER_ENV" && ok "readable by $APP_USER" || manual_step "$APP_USER cannot read $SERVER_ENV"
    local found; found=$(check_server_env "$SERVER_ENV" "$domain" || true)
    if [[ -z "$found" ]]; then ok "required settings present and valid (values not shown; the release reruns the app's own check)"
    else manual_step "installed settings need attention:"; sed 's/^/            /' <<<"$found"; fi
  elif [[ -z "$env_in" ]]; then
    manual_step "no settings yet: create them with make-server-env.mjs on the Mac and pass --server-env"
  fi

  section "Not changed by this script (checked only)"
  if command -v ufw >/dev/null && ufw status | grep -q '^Status: active'; then
    local rules; rules=$(ufw status)
    grep -qE '^(22|22/tcp|OpenSSH)\s+ALLOW' <<<"$rules" && ok "firewall allows SSH" || manual_step "firewall rules do not show SSH (22/OpenSSH) as allowed"
    grep -qE '^(Nginx Full|443|443/tcp|80,443/tcp)\s+ALLOW' <<<"$rules" && ok "firewall allows HTTPS" || manual_step "firewall rules do not show HTTPS (443/Nginx Full) as allowed"
  else warn "ufw is not active; check the provider firewall allows only 22, 80 and 443"; fi
  local busy; busy=$(ss -Htlnp '( sport = :3101 or sport = :3102 )' 2>/dev/null | grep -v 'node' || true)
  [[ -z "$busy" ]] && ok "release ports 3101/3102 free or used by the CRM" || manual_step "another program uses port 3101 or 3102"
  if command -v docker >/dev/null; then
    local published; published=$(docker ps --format '{{.Names}} {{.Ports}}' 2>/dev/null | grep -E ':(80|443|3101|3102)->' || true)
    [[ -z "$published" ]] && ok "Docker: $(docker ps -q 2>/dev/null | wc -l | tr -d ' ') running container(s), none on CRM ports (containers and volumes untouched)" \
      || manual_step "a Docker container publishes a CRM port: $published"
  fi
  # ahostsv6 also lists IPv4 addresses as ::ffff:a.b.c.d; only real IPv6 counts.
  getent ahostsv6 "$domain" 2>/dev/null | awk '{print $1}' | grep -vq '^::ffff:' && warn "$domain has an IPv6 address; the site template listens on IPv4 only" || ok "$domain has no IPv6 address (IPv4 listeners suffice)"

  section "GitHub secret DEPLOY_KNOWN_HOSTS (public host keys; compare fingerprints with your trusted record)"
  local hostkey
  for hostkey in /etc/ssh/ssh_host_ed25519_key.pub /etc/ssh/ssh_host_ecdsa_key.pub /etc/ssh/ssh_host_rsa_key.pub; do
    [[ -f "$hostkey" ]] && echo "  fingerprint $(ssh-keygen -lf "$hostkey" | awk '{print $2, $NF}')"
  done
  echo "  ---- paste the lines below into DEPLOY_KNOWN_HOSTS (DEPLOY_HOST must be exactly $deploy_host) ----"
  for hostkey in /etc/ssh/ssh_host_ed25519_key.pub /etc/ssh/ssh_host_ecdsa_key.pub /etc/ssh/ssh_host_rsa_key.pub; do
    [[ -f "$hostkey" ]] && printf '%s %s\n' "$deploy_host" "$(awk '{print $1, $2}' "$hostkey")"
  done
  echo "  ----"

  section "Result"
  if [[ "$mode" == apply ]]; then say DONE "$changed change(s) applied; run again without --apply to confirm"
  else say DONE "$todo item(s) to set up with --apply"; fi
  ((manual == 0)) || say MANUAL "$manual item(s) need a manual step (listed above)"
  echo "  Take and verify an encrypted backup (runbook section 2) before any release that changes the database."
  ((todo == 0 && manual == 0))
}

# Compares the secrets that must never change on an existing installation.
preserved_secrets_match() {
  python3 - "$1" "$2" <<'PY'
import re, sys
def read(path):
    values = {}
    for line in open(path, encoding="utf-8"):
        match = re.match(r"^([A-Za-z_][A-Za-z0-9_]*)=(.*)$", line.strip())
        if match:
            value = match.group(2)
            values[match.group(1)] = value[1:-1] if len(value) >= 2 and value[0] == value[-1] and value[0] in "'\"" else value
    return values
old, new = read(sys.argv[1]), read(sys.argv[2])
keys = ("ACCOUNTS_PIN_PEPPER", "ACCOUNT_OTP_SECRET", "META_TOKEN_ENCRYPTION_KEY")
sys.exit(0 if all(not old.get(k) or old.get(k) == new.get(k) for k in keys) else 1)
PY
}

# Installs the rate-limit file and site, disables competing sites, then
# validates and reloads Nginx. Any failure restores the previous state.
enable_site() {
  local domain=$1 tmp=$2; shift 2
  local undo=$tmp/nginx-undo entry moved=()
  mkdir -p "$undo"
  for entry in "$LIMITS" "$SITE"; do if [[ -f "$entry" ]]; then cp -p "$entry" "$undo/$(basename "$entry")"; fi; done
  local had_link=no; [[ -L "$SITE_LINK" ]] && had_link=yes
  install -d -o root -g root -m 755 "$DISABLED_SITES"
  for entry in "$@"; do
    local kept=$DISABLED_SITES/$(basename "$entry")
    [[ -e "$kept" || -L "$kept" ]] && kept=$kept.$(date +%Y%m%d%H%M%S)
    mv "$entry" "$kept"; moved+=("$kept")
    ok "disabled sites-enabled/$(basename "$entry") (kept as $kept)"
  done
  restore() {
    echo "Nginx rejected the new configuration; restoring the previous one" >&2
    for entry in "$LIMITS" "$SITE"; do
      if [[ -f "$undo/$(basename "$entry")" ]]; then cp -p "$undo/$(basename "$entry")" "$entry"; else rm -f "$entry"; fi
    done
    [[ "$had_link" == yes ]] || rm -f "$SITE_LINK"
    for entry in ${moved[@]+"${moved[@]}"}; do
      local name; name=$(basename "$entry"); mv "$entry" "/etc/nginx/sites-enabled/${name%.[0-9]*}"
    done
    nginx -t && systemctl reload nginx
    exit 1
  }
  if [[ -f "$LIMITS" ]] && ! cmp -s "$HERE/nginx.conf.example" "$LIMITS"; then cp -p "$LIMITS" "$LIMITS.previous"; fi
  install -o root -g root -m 644 "$HERE/nginx.conf.example" "$LIMITS"
  if [[ -f "$SITE" ]] && ! cmp -s "$tmp/site" "$SITE"; then cp -p "$SITE" "$SITE.previous"; fi
  install -o root -g root -m 644 "$tmp/site" "$SITE"
  ln -sfn "$SITE" "$SITE_LINK"
  nginx -t >/dev/null 2>&1 || restore
  systemctl reload nginx || restore
  ok "Nginx reloaded: https://$domain shows the 503 holding page until the first release"
}

